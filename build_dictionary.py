def build_bidirectional_dict(vocab):
    # Builds English -> Hebrew and Hebrew -> English mappings
    en_to_he = {}
    he_to_en = {}
    
    for en, he in vocab.items():
        en_clean = en.strip().lower()
        he_clean = he.strip()
        en_to_he[en_clean] = he_clean
        
        # Split multiple hebrew translations by comma / slash
        parts = [p.strip() for p in he_clean.replace('/', ',').split(',') if p.strip()]
        for p in parts:
            # Clean up punctuation/quotes
            p_clean = p.replace('"', '').replace("'", "").strip()
            if not p_clean:
                continue
            if p_clean not in he_to_en:
                he_to_en[p_clean] = []
            if en_clean not in he_to_en[p_clean]:
                he_to_en[p_clean].append(en_clean)
                
    # Flatten he_to_en list into comma-separated strings
    he_to_en_flat = {k: ", ".join(v) for k, v in he_to_en.items()}
    return en_to_he, he_to_en_flat

def main():
    vocab = load_base_vocabulary()
    en_to_he, he_to_en = build_bidirectional_dict(vocab)
    
    data = {
        "en_to_he": en_to_he,
        "he_to_en": he_to_en
    }
    
    out_file = "dict_data.json"
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=None)
        
    size_kb = os.path.getsize(out_file) / 1024
    print(f"Dictionary built successfully: {len(en_to_he)} EN words, {len(he_to_en)} HE words. File size: {size_kb:.1f} KB")

if __name__ == "__main__":
    main()
